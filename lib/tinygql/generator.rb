# frozen_string_literal: true

require "erb"
require "tinygql/schema"
require "tinygql/validating_parser"

module TinyGQL
  # Generates a recursive descent parser for queries against a schema.
  #
  #   File.write "my_parser.rb", TinyGQL::Generator.new(sdl).generate("MyParser")
  #
  #   require_relative "my_parser"
  #   MyParser.parse "{ user(id: 1) { name } }"
  class Generator
    INTROSPECTION = <<~GRAPHQL
      type __Schema {
        description: String
        types: [__Type!]!
        queryType: __Type!
        mutationType: __Type
        subscriptionType: __Type
        directives: [__Directive!]!
      }

      type __Type {
        kind: __TypeKind!
        name: String
        description: String
        fields(includeDeprecated: Boolean = false): [__Field!]
        interfaces: [__Type!]
        possibleTypes: [__Type!]
        enumValues(includeDeprecated: Boolean = false): [__EnumValue!]
        inputFields(includeDeprecated: Boolean = false): [__InputValue!]
        ofType: __Type
        specifiedByURL: String
        isOneOf: Boolean
      }

      enum __TypeKind {
        SCALAR
        OBJECT
        INTERFACE
        UNION
        ENUM
        INPUT_OBJECT
        LIST
        NON_NULL
      }

      type __Field {
        name: String!
        description: String
        args(includeDeprecated: Boolean = false): [__InputValue!]!
        type: __Type!
        isDeprecated: Boolean!
        deprecationReason: String
      }

      type __InputValue {
        name: String!
        description: String
        type: __Type!
        defaultValue: String
        isDeprecated: Boolean!
        deprecationReason: String
      }

      type __EnumValue {
        name: String!
        description: String
        isDeprecated: Boolean!
        deprecationReason: String
      }

      type __Directive {
        name: String!
        description: String
        locations: [__DirectiveLocation!]!
        args(includeDeprecated: Boolean = false): [__InputValue!]!
        isRepeatable: Boolean!
      }

      enum __DirectiveLocation {
        QUERY
        MUTATION
        SUBSCRIPTION
        FIELD
        FRAGMENT_DEFINITION
        FRAGMENT_SPREAD
        INLINE_FRAGMENT
        VARIABLE_DEFINITION
        SCHEMA
        SCALAR
        OBJECT
        FIELD_DEFINITION
        ARGUMENT_DEFINITION
        INTERFACE
        UNION
        ENUM
        ENUM_VALUE
        INPUT_OBJECT
        INPUT_FIELD_DEFINITION
      }
    GRAPHQL

    TYPENAME = Schema::Field.new("__typename", [], "String")
    SCHEMA_FIELD = Schema::Field.new("__schema", [], "__Schema")
    TYPE_FIELD = Schema::Field.new("__type", [Schema::Argument.new("name", true)], "__Type")

    TEMPLATE = File.join(__dir__, "generated_parser.erb")

    attr_reader :schema

    def initialize sdl
      @schema = Schema.parse(sdl + "\n" + INTROSPECTION)
    end

    # Ruby source for a file defining `class_name` as a parser for this schema
    def generate class_name
      <<~RUBY
        # frozen_string_literal: true

        # Generated by TinyGQL::Generator.  Do not edit.

        require "tinygql/validating_parser"

        class #{class_name} < TinyGQL::ValidatingParser
        #{body.gsub(/^(?!$)/, "  ").chomp}
        end
      RUBY
    end

    # An anonymous parser class for this schema
    def parser_class
      klass = Class.new(ValidatingParser)
      klass.class_eval "# frozen_string_literal: true\n#{body}", "(generated parser)"
      klass
    end

    # The body of the generated parser class
    def body
      @body ||= begin
        @argument_methods = []
        ERB.new(File.read(TEMPLATE), trim_mode: "-").result(binding)
      end
    end

    private

    def composite_types
      schema.types.each_value.select(&:composite?)
    end

    # Fields that can be selected on `type`, including meta fields
    def selectable_fields type
      fields = type.fields.values + [TYPENAME]
      fields += [SCHEMA_FIELD, TYPE_FIELD] if type.name == schema.roots["query"]
      fields
    end

    def abstract_types
      composite_types.reject { |t| t.kind == :object }
    end

    # Bit positions for object types that are possible types of some
    # interface or union
    def object_bits
      @object_bits ||= abstract_types.flat_map { |t| schema.possible_types(t.name) }
        .uniq.each_with_index.to_h
    end

    def possible_types_bitmap type_name
      bitmap = schema.possible_types(type_name).sum(0) { |name| 1 << object_bits.fetch(name) }
      "0x#{bitmap.to_s(16)}"
    end

    def composite? type_name
      schema[type_name].composite?
    end

    def selection_set_method type_name
      "selection_set_for_#{type_name}"
    end

    def field_method type_name
      "field_for_#{type_name}"
    end

    def fields_constant type_name
      "FIELDS_FOR_#{type_name}"
    end

    # Registers an argument parsing method for `field` and returns its name.
    # Methods are numbered because type and field names joined together
    # could collide.
    def argument_method type, field
      name = "arguments_#{@argument_methods.length}"
      @argument_methods << [name, type, field]
      name
    end

    def lit str
      str.dump
    end
  end
end
