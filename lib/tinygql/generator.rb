# frozen_string_literal: true

require "erb"
require "json"
require "tinygql/schema"
require "tinygql/validating_parser"

module TinyGQL
  # Generates a recursive descent parser for queries against a schema.
  #
  #   schema = TinyGQL.parse_schema(File.read("schema.graphql"))
  #   File.write "my_parser.rb", TinyGQL::Generator.new(schema).generate("MyParser")
  #
  #   require_relative "my_parser"
  #   MyParser.parse "{ user(id: 1) { name } }"
  class Generator
    # @rbs @body: String?
    # @rbs @argument_methods: Array[[String, Schema::Type, Schema::Field]]
    # @rbs @value_methods: Hash[String, [String, Nodes::NamedType | Nodes::ListType | Nodes::NotNullType]]
    # @rbs @object_methods: Hash[String, [String, Schema::Type]]
    # @rbs @object_bits: Hash[String, Integer]?
    # @rbs @field_types: Hash[String, [String, Nodes::NamedType | Nodes::ListType | Nodes::NotNullType]]
    # @rbs @field_arguments: Hash[Schema::Field, [String, Schema::Type]]
    # @rbs @introspection_indexes: Hash[String, Integer]?
    # @rbs @introspection_wrappers: Hash[String, [String, String, String]]

    NON_NULL_STRING = Nodes::NotNullType.new(0, Nodes::NamedType.new(0, "String")) #: Nodes::NotNullType
    TYPENAME = Schema::Field.new("__typename", [], NON_NULL_STRING) #: Schema::Field
    SCHEMA_FIELD = Schema::Field.new("__schema", [], Nodes::NotNullType.new(0, Nodes::NamedType.new(0, "__Schema"))) #: Schema::Field
    TYPE_FIELD = Schema::Field.new("__type", [Schema::InputValue.new("name", NON_NULL_STRING, nil)], Nodes::NamedType.new(0, "__Type")) #: Schema::Field

    # The tokens each built in scalar accepts, and the nodes they become
    BUILTIN_LITERALS = Ractor.make_shareable({
      "Int" => [[[:INT], "IntValue"]],
      "Float" => [[[:INT], "IntValue"], [[:FLOAT], "FloatValue"]],
      "String" => [[[:STRING], "StringValue"]],
      "Boolean" => [[[:TRUE, :FALSE], "BooleanValue"]],
      "ID" => [[[:STRING], "StringValue"], [[:INT], "IntValue"]],
    }) #: Hash[String, Array[[Array[Symbol], String]]]

    TEMPLATE = File.join(__dir__, "generated_parser.erb") #: String
    EXECUTOR_TEMPLATE = File.join(__dir__, "generated_executor.erb") #: String

    attr_reader :schema #: Schema

    # `document` is a schema AST from TinyGQL.parse_schema
    #: (Nodes::Document) -> void
    def initialize document
      @schema = Schema.new(document)
      unless @schema["__Schema"]
        raise Schema::Error, "Schema is missing the introspection types, parse it with TinyGQL.parse_schema"
      end
    end

    # Ruby source for a file defining `class_name` as a parser for this schema
    #: (String) -> String
    def generate class_name
      <<~RUBY
        # frozen_string_literal: true

        # Generated by TinyGQL::Generator.  Do not edit.

        require "tinygql/validating_parser"

        class #{class_name} < TinyGQL::ValidatingParser
        #{body.gsub(/^(?!$)/, "  ").chomp}
        end
      RUBY
    end

    # An anonymous parser class for this schema
    #: () -> singleton(ValidatingParser)
    def parser_class
      klass = Class.new(ValidatingParser)
      klass.class_eval "# frozen_string_literal: true\n#{body}", "(generated parser)"
      klass
    end

    # The body of the generated parser class
    #: () -> String
    def body
      @body ||= begin
        @argument_methods = []
        @value_methods = {}
        @object_methods = {}
        @field_types = {}
        @field_arguments = {}.compare_by_identity
        @introspection_wrappers = {}
        check_resolver_methods
        check_value_class_names
        parser = ERB.new(File.read(TEMPLATE), trim_mode: "-").result(binding)
        value_methods = @value_methods.length
        field_types = @field_types.length
        executor = ERB.new(File.read(EXECUTOR_TEMPLATE), trim_mode: "-").result(binding)
        # The parser template defines the TYPE_ and FIELD_TYPE_ constants
        # the executor uses
        raise "executor added value methods" unless value_methods == @value_methods.length
        raise "executor added field types" unless field_types == @field_types.length
        parser + executor
      end
    end

    private

    #: () -> Array[Schema::Type]
    def composite_types
      schema.types.each_value.select(&:composite?)
    end

    # Fields that can be selected on `type`, including meta fields
    #: (Schema::Type) -> Array[Schema::Field]
    def selectable_fields type
      resolved_fields(type) + [TYPENAME]
    end

    # Fields with resolver methods: the type's own, and __schema and __type
    # on the query type
    #: (Schema::Type) -> Array[Schema::Field]
    def resolved_fields type
      fields = type.fields.values
      fields += [SCHEMA_FIELD, TYPE_FIELD] if type.name == schema.roots["query"]
      fields
    end

    #: () -> Array[Schema::Type]
    def abstract_types
      composite_types.reject { |t| t.kind == :object }
    end

    # Bit positions for object types that are possible types of some
    # interface or union
    #: () -> Hash[String, Integer]
    def object_bits
      @object_bits ||= abstract_types.flat_map { |t| schema.possible_types(t.name) }
        .uniq.each_with_index.to_h
    end

    #: (String) -> String
    def possible_types_bitmap type_name
      bitmap = schema.possible_types(type_name).sum(0) { |name| 1 << object_bits.fetch(name) }
      "0x#{bitmap.to_s(16)}"
    end

    #: (String) -> bool
    def composite? type_name
      schema[type_name].composite?
    end

    #: (String) -> String
    def selection_set_method type_name
      "selection_set_for_#{type_name}"
    end

    #: (String) -> String
    def field_method type_name
      "field_for_#{type_name}"
    end

    #: (String) -> String
    def fields_constant type_name
      "FIELDS_FOR_#{type_name}"
    end

    # Registers an argument parsing method for `field` and returns its name.
    # Methods are numbered because type and field names joined together
    # could collide.
    #: (Schema::Type, Schema::Field) -> String
    def argument_method type, field
      name = "arguments_#{@argument_methods.length}"
      @argument_methods << [name, type, field]
      name
    end

    # Registers a method that parses values of `type`, a type node, and
    # returns its name.  Each distinct type, like "[ID!]", gets one method.
    # Wrapped types and input object fields are registered too, so every
    # method exists before the template renders them.
    #: (Nodes::NamedType | Nodes::ListType | Nodes::NotNullType) -> String
    def value_method type
      key = Schema.type_string(type)
      return @value_methods[key].first if @value_methods.key?(key)

      name = "value_#{@value_methods.length}"
      @value_methods[key] = [name, type]
      if type.named_type?
        named = schema[type.name]
        named.fields.each_value { |field| value_method field.type } if named.kind == :input
      else
        value_method type.type
      end
      name
    end

    # Code that parses the value of argument or input field `input`.
    # `const` is Ruby code for whether variables are disallowed.  A nullable
    # variable may be used for a non-null input with a default, so those
    # check variables against the nullable type
    #: (Schema::InputValue) -> String
    def input_value input, const
      method = value_method input.type
      if input.type.not_null_type? && input.default_value
        "at?(:VAR_SIGN) ? variable_usage(#{type_constant input.type.type}, #{const}) : #{method}(#{const})"
      else
        "#{method} #{const}"
      end
    end

    # The constant holding the type node for value method of `type`.
    # Variable usages are checked against it
    #: (Nodes::NamedType | Nodes::ListType | Nodes::NotNullType) -> String
    def type_constant type
      "TYPE_#{value_method(type).delete_prefix("value_")}"
    end

    # Ruby code that builds a node for `type`
    #: (Nodes::NamedType | Nodes::ListType | Nodes::NotNullType) -> String
    def type_node type
      if type.not_null_type?
        "TinyGQL::Nodes::NotNullType.new(0, #{type_node type.type})"
      elsif type.list_type?
        "TinyGQL::Nodes::ListType.new(0, #{type_node type.type})"
      else
        "TinyGQL::Nodes::NamedType.new(0, #{lit type.name})"
      end
    end

    # Registers a method that parses object values of input type `name`
    #: (String) -> String
    def object_method name
      @object_methods[name] ||= ["object_value_for_#{name}", schema[name]]
      @object_methods[name].first
    end

    # Enum types that value methods check
    #: () -> Array[Schema::Type]
    def input_enums
      @value_methods.each_value.filter_map { |_, type|
        type.named_type? && schema[type.name].kind == :enum ? schema[type.name] : nil
      }
    end

    #: (String) -> String
    def coerce_object_method type_name
      "coerce_object_#{type_name}"
    end

    #: (String) -> String
    def literal_object_method type_name
      "literal_object_#{type_name}"
    end

    LITERAL_KINDS = {
      Nodes::IntValue => :INT,
      Nodes::FloatValue => :FLOAT,
      Nodes::StringValue => :STRING,
      Nodes::BooleanValue => :BOOLEAN,
      Nodes::EnumValue => :ENUM,
      Nodes::ListValue => :LIST,
      Nodes::ObjectValue => :OBJECT,
    }.freeze #: Hash[singleton(Nodes::Node), Symbol]

    # Ruby code for the value of a schema default, `node` of `type`.  The
    # schema's literals weren't coerced when it was parsed, so this calls
    # the scalars each time a default is used
    #: (Nodes::NamedType | Nodes::ListType | Nodes::NotNullType, Nodes::Value | Nodes::ObjectValue | Nodes::Variable, ?Array[String]) -> String
    def default_code type, node, seen = []
      return "nil" if node.null_value?

      if type.not_null_type?
        default_code type.type, node, seen
      elsif type.list_type?
        items = node.list_value? ? node.value : [node]
        "[#{items.map { default_code(type.type, _1, seen) }.join(", ")}].freeze"
      else
        named = schema[type.name]
        case named.kind
        when :enum
          lit node.value
        when :scalar
          if BUILTIN_LITERALS.key?(named.name)
            "@scalars.coerce_literal_#{named.name}(#{lit node.value})"
          else
            kind = LITERAL_KINDS.fetch(node.class)
            text = kind == :LIST || kind == :OBJECT ? node_code(node) : lit(node.value)
            "@scalars.coerce_literal_#{named.name}(:#{kind}, #{text})"
          end
        else
          # Defaults of input objects can leave out fields that have
          # defaults of their own, which could refer back to this type
          if seen.include?(named.name)
            raise Schema::Error, "Default value of #{named.name} refers to itself"
          end
          given = node.values.to_h { [_1.name, _1.value] }
          values = named.fields.each_value.map do |field|
            value = given.fetch(field.name) { field.default_value }
            value ? default_code(field.type, value, seen + [named.name]) : "nil"
          end
          "#{input_class named.name}.new(#{values.join(", ")})"
        end
      end
    end

    # Ruby code that builds value node `node`, for custom scalar defaults
    #: (Nodes::Value | Nodes::ObjectValue | Nodes::Variable) -> String
    def node_code node
      case node
      when Nodes::ListValue
        "TinyGQL::Nodes::ListValue.new(0, [#{node.value.map { node_code _1 }.join(", ")}].freeze, nil)"
      when Nodes::ObjectValue
        fields = node.values.map { "TinyGQL::Nodes::ObjectField.new(0, #{lit _1.name}, #{node_code _1.value})" }
        "TinyGQL::Nodes::ObjectValue.new(0, [#{fields.join(", ")}].freeze, nil)"
      else
        "TinyGQL::Nodes::#{node.class.name.split("::").last}.new(0, #{lit node.value}, nil)"
      end
    end

    #: () -> Array[Schema::Type]
    def input_objects
      input_types.select { |t| t.kind == :input }
    end

    # Types that variables can be declared with
    #: () -> Array[Schema::Type]
    def input_types
      schema.types.each_value.select(&:input?)
    end

    #: (String) -> String
    def enum_constant type_name
      "ENUM_VALUES_#{type_name}"
    end

    # Types that fields can return
    #: () -> Array[Schema::Type]
    def output_types
      schema.types.each_value.select { |t| t.composite? || t.kind == :scalar || t.kind == :enum }
    end

    # Whether `type` is one of the introspection types, like __Type
    #: (Schema::Type) -> bool
    def introspection_type? type
      type.name.start_with?("__")
    end

    #: () -> Array[Schema::Type]
    def object_types
      output_types.select { |t| t.kind == :object }
    end

    # Enums that only fields return, whose ENUM_VALUES_ constants the
    # parser template didn't define
    #: () -> Array[Schema::Type]
    def output_enums
      output_types.select { |t| t.kind == :enum } - input_enums
    end

    #: (String) -> String
    def execute_method type_name
      "execute_#{type_name}"
    end

    #: (String) -> String
    def execute_field_method type_name
      "execute_field_#{type_name}"
    end

    #: (String) -> String
    def execute_fields_constant type_name
      "EXECUTE_FIELDS_#{type_name}"
    end

    #: (String, String) -> String
    def resolver_method type_name, field_name
      "#{type_name}_#{field_name}"
    end

    # Resolver methods join type and field names, so `A_b.c` and `A.b_c`
    # would both be `A_b_c`
    #: () -> void
    def check_resolver_methods
      seen = {}
      abstract_types.each { |type| seen["resolve_type_#{type.name}"] = type.name }
      object_types.each do |type|
        resolved_fields(type).each do |field|
          name = resolver_method(type.name, field.name)
          if seen.key?(name)
            raise Schema::Error, "Resolver method #{name} for #{type.name}.#{field.name} collides with #{seen[name]}"
          end
          seen[name] = "#{type.name}.#{field.name}"
        end
      end
    end

    # The class that values of input object type `type_name` become
    #: (String) -> String
    def input_class type_name
      "InputObjects::#{type_name}"
    end

    # The class that the arguments of `type_name`.`field_name` become
    #: (String, String) -> String
    def arguments_class type_name, field_name
      "Arguments::#{arguments_class_name type_name, field_name}"
    end

    # The resolver method's name, except introspection types start with
    # "__", which constants can't
    #: (String, String) -> String
    def arguments_class_name type_name, field_name
      name = resolver_method(type_name, field_name)
      name.start_with?("__") ? "Introspection#{name}" : name
    end

    # Input objects and arguments become classes with a reader for each
    # field, so their names must be constants
    #: () -> void
    def check_value_class_names
      classes = input_objects.map { [_1.name, _1.name, _1.fields.values] }
      seen = {}
      object_types.each do |type|
        resolved_fields(type).each do |field|
          next if field.arguments.empty?
          name = arguments_class_name(type.name, field.name)
          if seen.key?(name)
            raise Schema::Error, "Arguments class #{name} for #{type.name}.#{field.name} collides with #{seen[name]}"
          end
          seen[name] = "#{type.name}.#{field.name}"
          classes << [name, "#{type.name}.#{field.name}", field.arguments]
        end
      end
      classes.each do |class_name, name, inputs|
        unless class_name.match?(/\A[A-Z]/)
          raise Schema::Error, "#{name} must start with an uppercase letter to be a Ruby class"
        end
      end
    end

    # Ruby code for a frozen class with a reader for each of `inputs`,
    # indented by `indent`.  The initializer takes the values positionally,
    # since field names like `in` aren't valid parameter names
    #: (String, Array[Schema::InputValue], String) -> String
    def value_class name, inputs, indent
      params = inputs.each_index.map { "f#{_1}" }
      lines = ["class #{name}"]
      inputs.each { |input| lines << "  attr_reader :#{input.name} #: #{rbs_type input.type}" }
      lines << ""
      lines << "  #: (#{inputs.map { rbs_type _1.type }.join(", ")}) -> void"
      lines << "  def initialize #{params.join(", ")}"
      inputs.each_with_index { |input, i| lines << "    @#{input.name} = f#{i}" }
      lines << "    freeze"
      lines << "  end"
      lines << "end"
      lines.map { _1.empty? ? _1 : indent + _1 }.join("\n")
    end

    # The RBS type of coerced values of `type`
    #: (Nodes::NamedType | Nodes::ListType | Nodes::NotNullType, ?bool) -> String
    def rbs_type type, nullable = true
      return rbs_type(type.type, false) if type.not_null_type?

      rbs = if type.list_type?
        "Array[#{rbs_type type.type}]"
      else
        case type.name
        when "Int" then "Integer"
        when "Float" then "Float"
        when "String", "ID" then "String"
        when "Boolean" then "bool"
        else
          case schema[type.name].kind
          when :enum then "String"
          when :input then input_class(type.name)
          else return "untyped"
          end
        end
      end
      nullable ? "#{rbs}?" : rbs
    end

    # Registers a constant holding the type node of an output field's type
    # and returns its name.  Fields are checked for merging with it, and
    # their results are completed with it
    #: (Nodes::NamedType | Nodes::ListType | Nodes::NotNullType) -> String
    def field_type_constant type
      key = Schema.type_string(type)
      @field_types[key] ||= ["FIELD_TYPE_#{@field_types.length}", type]
      @field_types[key].first
    end

    # Registers a method that builds the arguments of `type`.`field`
    #: (Schema::Type, Schema::Field) -> String
    def field_arguments_method type, field
      (@field_arguments[field] ||= ["field_arguments_#{@field_arguments.length}", type]).first
    end

    #: () -> Array[Schema::Type]
    def custom_scalars
      schema.types.each_value.select { |t| t.kind == :scalar && !Schema::BUILTIN_SCALARS.include?(t.name) }
    end

    TYPE_KINDS = {
      object: "OBJECT",
      interface: "INTERFACE",
      union: "UNION",
      scalar: "SCALAR",
      enum: "ENUM",
      input: "INPUT_OBJECT",
    }.freeze #: Hash[Symbol, String]

    # The local variable in the generated Introspection module for type node
    # `type`.  Wrapped types, like "[ID!]", are registered so the template
    # can define them before they're used
    #: (Nodes::NamedType | Nodes::ListType | Nodes::NotNullType) -> String
    def introspection_ref type
      return introspection_variable(type.name) if type.named_type?

      key = Schema.type_string(type)
      unless @introspection_wrappers.key?(key)
        inner = introspection_ref(type.type)
        kind = type.not_null_type? ? "NON_NULL" : "LIST"
        @introspection_wrappers[key] = ["wrapped_#{@introspection_wrappers.length}", kind, inner]
      end
      @introspection_wrappers[key].first
    end

    # The local variable in the generated Introspection module for named
    # type `name`.  These aren't constants because filling a constant cache
    # checks whether the value is Ractor shareable, which walks every type
    # reachable from a frozen one
    #: (String) -> String
    def introspection_variable name
      @introspection_indexes ||= schema.types.each_key.with_index.to_h
      "type_#{@introspection_indexes.fetch(name)}"
    end

    # Ruby code that builds `type`'s Introspection::Type, before its lists
    # are defined
    #: (Schema::Type) -> String
    def introspection_type type
      specified_by = type.kind == :scalar ? lit_or_nil(type.specified_by_url) : "nil"
      one_of = type.kind == :input ? type.one_of.to_s : "nil"
      "Type.new(#{lit TYPE_KINDS.fetch(type.kind)}, #{lit type.name}, #{lit_or_nil type.description}, #{specified_by}, #{one_of})"
    end

    # Ruby code that defines `type`'s lists, indented by `indent`
    #: (Schema::Type, String) -> String
    def introspection_define type, indent
      fields = interfaces = possible_types = enum_values = input_fields = "nil"
      case type.kind
      when :object, :interface
        fields = introspection_list(type.fields.each_value.map { introspection_field _1, "#{indent}  " }, indent)
        interfaces = introspection_list(type.interfaces.map { introspection_variable _1 }, indent)
      when :enum
        enum_values = introspection_list(type.values.each_value.map { |value|
          "EnumValue.new(#{lit value.name}, #{lit_or_nil value.description}, #{lit_or_nil value.deprecation_reason})"
        }, indent)
      when :input
        input_fields = introspection_list(type.fields.each_value.map { introspection_input _1 }, indent)
      end
      if type.kind == :interface || type.kind == :union
        possible_types = introspection_list(schema.possible_types(type.name).map { introspection_variable _1 }, indent)
      end
      "#{introspection_variable type.name}.define(#{fields}, #{interfaces}, #{possible_types}, #{enum_values}, #{input_fields})"
    end

    # Ruby code that builds `directive`'s Introspection::Directive
    #: (Schema::Directive, String) -> String
    def introspection_directive directive, indent
      locations = "[#{directive.locations.map { lit _1 }.join(", ")}]"
      args = introspection_list(directive.arguments.map { introspection_input _1 }, indent)
      "Directive.new(#{lit directive.name}, #{lit_or_nil directive.description}, #{locations}, #{args}, #{directive.repeatable})"
    end

    #: (Schema::Field, String) -> String
    def introspection_field field, indent
      args = introspection_list(field.arguments.map { introspection_input _1 }, indent)
      "Field.new(#{lit field.name}, #{lit_or_nil field.description}, #{args}, #{introspection_ref field.type}, #{lit_or_nil field.deprecation_reason})"
    end

    #: (Schema::InputValue) -> String
    def introspection_input input
      default = input.default_value ? lit(graphql_value(input.default_value)) : "nil"
      "InputValue.new(#{lit input.name}, #{lit_or_nil input.description}, #{introspection_ref input.type}, #{default}, #{lit_or_nil input.deprecation_reason})"
    end

    # An array of `items`, one per line, or EMPTY
    #: (Array[String], String) -> String
    def introspection_list items, indent
      return "EMPTY" if items.empty?
      return "[#{items.first}]" if items.length == 1 && items.first.length < 60
      "[\n#{items.map { "#{indent}  #{_1},\n" }.join}#{indent}]"
    end

    # Value node `node` printed as GraphQL, for defaultValue
    #: (Nodes::Value | Nodes::ObjectValue | Nodes::Variable) -> String
    def graphql_value node
      case node
      when Nodes::NullValue then "null"
      when Nodes::StringValue then JSON.generate(node.value)
      when Nodes::ListValue then "[#{node.value.map { graphql_value _1 }.join(", ")}]"
      when Nodes::ObjectValue then "{#{node.values.map { "#{_1.name}: #{graphql_value _1.value}" }.join(", ")}}"
      else node.value
      end
    end

    #: (String?) -> String
    def lit_or_nil str
      str ? lit(str) : "nil"
    end

    #: (String) -> String
    def lit str
      str.dump
    end
  end
end
